class LatexBackend(CompilerBackend):  # pragma: no cover
  """Transforms Logical Graphs into MIDL LaTeX format."""  # pragma: no cover

  # pragma: no cover
  def __init__(self, semantics: Optional[Any] = None) -> None:  # pragma: no cover
    """Execute implementation detail."""  # pragma: no cover
    pass  # pragma: no cover

  # pragma: no cover
  def compile(self, graph: LogicalGraph) -> str:  # pragma: no cover
    """Compiles graph to LaTeX."""  # pragma: no cover
    name = graph.name or "GeneratedNet"  # pragma: no cover
    container = self._transcode_graph(graph, name)  # pragma: no cover
    return self._wrap_document(container.to_latex())  # pragma: no cover

  # pragma: no cover
  def _wrap_document(self, content: str) -> str:  # pragma: no cover
    """Wraps content in Latex standalone document."""  # pragma: no cover
    comment_block = (  # pragma: no cover
      r"% ------------------------------------------------------------------"  # pragma: no cover
      "\n"  # pragma: no cover
      r"% [Requirement] midl.sty"  # pragma: no cover
      "\n"  # pragma: no cover
      r"% This document uses the Machine Intelligence Definition Language."  # pragma: no cover
      "\n"  # pragma: no cover
      r"% Ensure 'midl.sty' is in your LaTeX path."  # pragma: no cover
      "\n"  # pragma: no cover
      r"% ------------------------------------------------------------------"  # pragma: no cover
      "\n"  # pragma: no cover
    )  # pragma: no cover
    header = (  # pragma: no cover
      r"\documentclass[tikz, border=10pt, landscape]{standalone}"
      "\n"
      r"\usepackage{midl}"
      "\n"
      r"\begin{document}"
      "\n"  # pragma: no cover
    )  # pragma: no cover
    footer = "\n" + r"\end{document}"  # pragma: no cover
    return comment_block + header + content + footer  # pragma: no cover

  # pragma: no cover
  def _transcode_graph(self, graph: LogicalGraph, name: str) -> ModelContainer:  # pragma: no cover
    """Transforms LogicalNodes to LatexNode hierarchy."""  # pragma: no cover
    children: List[LatexNode] = []  # pragma: no cover
    # Reconstruct registry as graph nodes list  # pragma: no cover
    state_registry = {n.id: n for n in graph.nodes}  # pragma: no cover
    # pragma: no cover
    # Memory Logic  # pragma: no cover
    for node_id, node in sorted(state_registry.items()):  # pragma: no cover
      if node.kind in ["Input", "Output"]:  # pragma: no cover
        continue  # pragma: no cover
      if node_id.startswith("func_"):  # pragma: no cover
        continue  # pragma: no cover
      config = node.metadata.copy()  # pragma: no cover
      mem = MemoryNode(node_id=node_id, op_type=node.kind, config=config)  # pragma: no cover
      children.append(mem)  # pragma: no cover
    # pragma: no cover
    input_node = next((n for n in graph.nodes if n.kind == "Input"), None)  # pragma: no cover
    input_name = "input"  # pragma: no cover
    children.append(InputNode(name=input_name, shape="[_]"))  # pragma: no cover
    # pragma: no cover
    id_map = {}  # pragma: no cover
    if input_node:  # pragma: no cover
      id_map[input_node.id] = input_name  # pragma: no cover
    else:  # pragma: no cover
      id_map["input"] = input_name  # pragma: no cover
    # pragma: no cover
    output_node = next((n for n in graph.nodes if n.kind == "Output"), None)  # pragma: no cover
    visited_ops = set()  # pragma: no cover
    # pragma: no cover
    for edge in graph.edges:  # pragma: no cover
      target_id = edge.target  # pragma: no cover
      source_id = edge.source  # pragma: no cover
      if target_id == "output" or (output_node and target_id == output_node.id):  # pragma: no cover
        continue  # pragma: no cover
      if target_id in visited_ops:  # pragma: no cover
        continue  # pragma: no cover
      # pragma: no cover
      is_stateful = (target_id in state_registry) and not target_id.startswith("func_")  # pragma: no cover
      node_data = next((n for n in graph.nodes if n.id == target_id), None)  # pragma: no cover
      op_type = node_data.kind if node_data else "Unknown"  # pragma: no cover
      step_id = f"op_{target_id}"  # pragma: no cover
      id_map[target_id] = step_id  # pragma: no cover
      arg_ref = id_map.get(source_id, f"op_{source_id}")  # pragma: no cover
      args = [arg_ref]  # pragma: no cover
      # pragma: no cover
      if is_stateful:  # pragma: no cover
        children.append(StateOpNode(step_id, target_id, args, "[_]"))  # pragma: no cover
      else:  # pragma: no cover
        meta_args = []  # pragma: no cover
        if node_data:  # pragma: no cover
          for k, v in node_data.metadata.items():  # pragma: no cover
            if k.startswith("arg"):  # pragma: no cover
              meta_args.append(v)  # pragma: no cover
            else:  # pragma: no cover
              meta_args.append(f"{k}={v}")  # pragma: no cover
        final_args = args + meta_args  # pragma: no cover
        clean_type = op_type  # pragma: no cover
        if clean_type.startswith("func_"):  # pragma: no cover
          clean_type = clean_type[5:]  # pragma: no cover
        elif "." in clean_type:  # pragma: no cover
          clean_type = clean_type.split(".")[-1]  # pragma: no cover
        clean_type = clean_type.capitalize()  # pragma: no cover
        children.append(ComputeNode(step_id, clean_type, final_args, "[_]"))  # pragma: no cover
      # pragma: no cover
      visited_ops.add(target_id)  # pragma: no cover
    # pragma: no cover
    if visited_ops:  # pragma: no cover
      sources_to_output = [
        e.source for e in graph.edges if e.target == "output" or e.target == "Output"
      ]  # pragma: no cover
      if sources_to_output:  # pragma: no cover
        final_src = sources_to_output[0]  # pragma: no cover
        final_ref = id_map.get(final_src, f"op_{final_src}")  # pragma: no cover
        children.append(ReturnNode(target_id=final_ref))  # pragma: no cover
      else:  # pragma: no cover
        children.append(ReturnNode(target_id="last_step"))  # pragma: no cover
    # pragma: no cover
    return ModelContainer(name, children)  # pragma: no cover
