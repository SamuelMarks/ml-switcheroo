class TikzBackend(CompilerBackend):  # pragma: no cover
  """Orchestrates the conversion of a LogicalGraph to TikZ source code.  # pragma: no cover
  Verified to use Rank-Based Layout.  # pragma: no cover
  """  # pragma: no cover

  # pragma: no cover
  def __init__(
    self, semantics: Optional[Any] = None, y_spacing: float = 2.5, x_spacing: float = 3.0
  ) -> None:  # pragma: no cover
    """Initialize TikZ backend.  # pragma: no cover
    # pragma: no cover
    Args:  # pragma: no cover
        semantics: Unused.  # pragma: no cover
        y_spacing: Vertical space between ranks.  # pragma: no cover
        x_spacing: Horizontal space between nodes.  # pragma: no cover
    # pragma: no cover
    """  # pragma: no cover
    self.y_spacing = y_spacing  # pragma: no cover
    self.x_spacing = x_spacing  # pragma: no cover

  # pragma: no cover
  def compile(self, graph: LogicalGraph) -> str:  # pragma: no cover
    """Compile graph to TikZ LaTeX code."""  # pragma: no cover
    positions = self._calculate_layout(graph)  # pragma: no cover
    cst_nodes = []  # pragma: no cover
    cst_nodes.append(TikzComment("Generated by ml-switcheroo"))  # pragma: no cover
    cst_nodes.append(TriviaNode("\n"))  # type: ignore  # pragma: no cover
    # pragma: no cover
    for node in graph.nodes:  # pragma: no cover
      pos = positions.get(node.id, (0, 0))  # pragma: no cover
      tikz_node = self._create_tikz_node(node, pos[0], pos[1])  # pragma: no cover
      cst_nodes.append(tikz_node)  # type: ignore  # pragma: no cover
    # pragma: no cover
    cst_nodes.append(TriviaNode("\n"))  # type: ignore  # pragma: no cover
    # pragma: no cover
    for edge in graph.edges:  # pragma: no cover
      tikz_edge = self._create_tikz_edge(edge)  # pragma: no cover
      cst_nodes.append(tikz_edge)  # type: ignore  # pragma: no cover
    # pragma: no cover
    options = [  # pragma: no cover
      TikzOption("node distance", "2cm"),  # pragma: no cover
      TikzOption("auto"),  # pragma: no cover
      TikzOption(">=stealth"),  # pragma: no cover
    ]  # pragma: no cover
    root = TikzGraph(children=cst_nodes, options=options)  # type: ignore  # pragma: no cover
    return root.to_text()  # pragma: no cover

  # pragma: no cover
  def _sanitize(self, text: str) -> str:  # pragma: no cover
    """Escape special LaTeX characters."""  # pragma: no cover
    return str(text).replace("_", r"\_")  # pragma: no cover

  # pragma: no cover
  def _calculate_layout(self, graph: LogicalGraph) -> Dict[str, Tuple[float, float]]:  # pragma: no cover
    """Determine X,Y coordinates for nodes based on topological rank."""  # pragma: no cover
    if not graph.nodes:  # pragma: no cover
      return {}  # pragma: no cover
    # pragma: no cover
    adj = defaultdict(list)  # pragma: no cover
    in_degree = defaultdict(int)  # pragma: no cover
    for n in graph.nodes:  # pragma: no cover
      in_degree[n.id] = 0  # pragma: no cover
    # pragma: no cover
    for edge in graph.edges:  # pragma: no cover
      adj[edge.source].append(edge.target)  # pragma: no cover
      in_degree[edge.target] += 1  # pragma: no cover
    # pragma: no cover
    queue = deque([n.id for n in graph.nodes if in_degree[n.id] == 0])  # pragma: no cover
    ranks = {}  # pragma: no cover
    processed = set()  # pragma: no cover
    # pragma: no cover
    if not queue and graph.nodes:  # pragma: no cover
      first = graph.nodes[0].id  # pragma: no cover
      queue.append(first)  # pragma: no cover
      ranks[first] = 0  # pragma: no cover
    else:  # pragma: no cover
      for root_id in queue:  # pragma: no cover
        ranks[root_id] = 0  # pragma: no cover
    # pragma: no cover
    max_rank = 0  # pragma: no cover
    while queue:  # pragma: no cover
      curr = queue.popleft()  # pragma: no cover
      if curr in processed:  # pragma: no cover
        continue  # pragma: no cover
      processed.add(curr)  # pragma: no cover
      curr_rank = ranks.get(curr, 0)  # pragma: no cover
      max_rank = max(max_rank, curr_rank)  # pragma: no cover
      # pragma: no cover
      for neighbor in adj[curr]:  # pragma: no cover
        if neighbor not in ranks or ranks[neighbor] < curr_rank + 1:  # pragma: no cover
          ranks[neighbor] = curr_rank + 1  # pragma: no cover
          queue.append(neighbor)  # pragma: no cover
    # pragma: no cover
    for n in graph.nodes:  # pragma: no cover
      if n.id not in ranks:  # pragma: no cover
        max_rank += 1  # pragma: no cover
        ranks[n.id] = max_rank  # pragma: no cover
    # pragma: no cover
    rank_groups = defaultdict(list)  # pragma: no cover
    for node_id, r in ranks.items():  # pragma: no cover
      rank_groups[r].append(node_id)  # pragma: no cover
    # pragma: no cover
    positions = {}  # pragma: no cover
    for r, nodes in rank_groups.items():  # pragma: no cover
      y = -r * self.y_spacing  # pragma: no cover
      count = len(nodes)  # pragma: no cover
      start_x = -((count - 1) * self.x_spacing) / 2  # pragma: no cover
      for i, node_id in enumerate(nodes):  # pragma: no cover
        x = start_x + (i * self.x_spacing)  # pragma: no cover
        positions[node_id] = (x, y)  # pragma: no cover
    return positions  # pragma: no cover

  # pragma: no cover
  def _create_tikz_node(self, node: LogicalNode, x: float, y: float) -> TikzNode:  # pragma: no cover
    """Creates a TikzNode AST object."""  # pragma: no cover
    options = [  # pragma: no cover
      TikzOption("draw"),  # pragma: no cover
      TikzOption("rectangle"),  # pragma: no cover
      TikzOption("rounded corners"),  # pragma: no cover
      TikzOption("align", "center"),  # pragma: no cover
    ]  # pragma: no cover
    if node.kind == "Input":  # pragma: no cover
      options.append(TikzOption("fill", "green!10"))  # pragma: no cover
    elif node.kind == "Output":  # pragma: no cover
      options.append(TikzOption("fill", "red!10"))  # pragma: no cover
    else:  # pragma: no cover
      options.append(TikzOption("fill", "blue!5"))  # pragma: no cover
    # pragma: no cover
    sanitized_kind = self._sanitize(node.kind)  # pragma: no cover
    rows = [[rf"\textbf{{{sanitized_kind}}}"]]  # pragma: no cover
    sanitized_id = self._sanitize(node.id)  # pragma: no cover
    rows.append([rf"\textit{{{sanitized_id}}}"])  # pragma: no cover
    # pragma: no cover
    for k, v in node.metadata.items():  # pragma: no cover
      clean_k = self._sanitize(k)  # pragma: no cover
      clean_v = self._sanitize(str(v)[:20])  # pragma: no cover
      rows.append([f"{clean_k}: {clean_v}"])  # pragma: no cover
    # pragma: no cover
    content_table = TikzTable(rows=rows, align="c")  # pragma: no cover
    # pragma: no cover
    return TikzNode(  # pragma: no cover
      node_id=node.id,  # pragma: no cover
      x=x,  # pragma: no cover
      y=y,  # pragma: no cover
      content=content_table,  # pragma: no cover
      options=options,  # pragma: no cover
    )  # pragma: no cover

  # pragma: no cover
  def _create_tikz_edge(self, edge: LogicalEdge) -> TikzEdge:  # pragma: no cover
    """Creates a TikzEdge AST object."""  # pragma: no cover
    return TikzEdge(  # pragma: no cover
      source_id=edge.source,  # pragma: no cover
      target_id=edge.target,  # pragma: no cover
      connector="--",  # pragma: no cover
      options=[TikzOption("->"), TikzOption("thick")],  # pragma: no cover
    )  # pragma: no cover

  # pragma: no cover
