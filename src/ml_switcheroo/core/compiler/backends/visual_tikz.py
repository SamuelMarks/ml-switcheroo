"""TikZ visualizer backend for LogicalGraphs.

This module provides the TikzBackend, which converts LogicalGraphs into
TikZ LaTeX diagrams, calculating a rank-based layout for node positioning
and generating a compileable TikZ abstract syntax tree.
"""

from collections import defaultdict, deque
import typing

from ml_switcheroo.core.compiler.backend import CompilerBackend
from ml_switcheroo.core.compiler.ir import LogicalEdge, LogicalGraph, LogicalNode
from ml_switcheroo.core.tikz.nodes import (
  TikzBaseNode,
  TikzEdge,
  TikzGraph,
  TikzNode,
  TikzOption,
  TikzTable,
  TikzTextNode,
  TriviaNode,
)

if typing.TYPE_CHECKING:
  from ml_switcheroo.semantics.manager import SemanticsManager


class TikzBackend(CompilerBackend):
  """Orchestrate the conversion of a LogicalGraph to TikZ source code.

  Verified to use Rank-Based Layout.
  """

  def __init__(
    self,
    semantics: "SemanticsManager | None" = None,
    y_spacing: float = 2.5,
    x_spacing: float = 3.0,
  ) -> None:
    """Initialize the TikZ backend with layout spacing parameters.

    Args:
        semantics: Optional semantics manager for operator resolution.
        y_spacing: Vertical space between topological ranks. Defaults to 2.5.
        x_spacing: Horizontal space between sibling nodes. Defaults to 3.0.
    """
    super().__init__(semantics=semantics)
    self.y_spacing = y_spacing
    self.x_spacing = x_spacing

  def compile(self, graph: LogicalGraph) -> str:
    """Compile a LogicalGraph to TikZ LaTeX code.

    Args:
        graph: The logical graph structure to be compiled.

    Returns:
        str: The generated TikZ LaTeX source code string representing the graph.
    """
    positions = self._calculate_layout(graph)
    cst_nodes: list[TikzBaseNode] = []
    cst_nodes.append(TriviaNode("% Generated by ml-switcheroo" + chr(10), kind="comment"))

    for node in graph.nodes.values():
      pos = positions.get(node.id, (0, 0))
      tikz_node = self._create_tikz_node(node, pos[0], pos[1])
      cst_nodes.append(tikz_node)

    for edge in graph.edges:
      tikz_edge = self._create_tikz_edge(edge)
      cst_nodes.append(tikz_edge)

    options = [
      TikzOption("node distance", "2cm"),
      TikzOption("auto"),
      TikzOption(">=stealth"),
    ]
    root = TikzGraph(children=cst_nodes, options=options)
    return root.to_text()

  def _sanitize(self, text: str) -> str:
    """Escape special LaTeX characters in a given string.

    Args:
        text: The raw string to be sanitized.

    Returns:
        str: The sanitized string with special characters properly escaped.
    """
    return str(text).replace("_", chr(92) + "_")

  def _calculate_layout(self, graph: LogicalGraph) -> dict[str, tuple[float, float]]:
    """Determine X, Y coordinates for nodes based on topological rank.

    Args:
        graph: The logical graph whose layout is to be calculated.

    Returns:
        Dict[str, Tuple[float, float]]: Mapping of node IDs to (x, y) coordinates.
    """
    if not graph.nodes:
      return {}

    adj = defaultdict(list)
    in_degree = defaultdict(int)
    for n in graph.nodes.values():
      in_degree[n.id] = 0

    for edge in graph.edges:
      adj[edge.source].append(edge.target)
      in_degree[edge.target] += 1

    queue = deque([n.id for n in graph.nodes.values() if in_degree[n.id] == 0])
    ranks = {}
    processed = set()

    if not queue and graph.nodes:
      first = next(iter(graph.nodes.values())).id
      queue.append(first)
      ranks[first] = 0
    else:
      for root_id in queue:
        ranks[root_id] = 0

    max_rank = 0
    while queue:
      curr = queue.popleft()
      if curr in processed:
        continue
      processed.add(curr)
      curr_rank = ranks.get(curr, 0)
      max_rank = max(max_rank, curr_rank)

      for neighbor in adj[curr]:
        if neighbor not in ranks or ranks[neighbor] < curr_rank + 1:
          ranks[neighbor] = curr_rank + 1
          queue.append(neighbor)

    for n in graph.nodes.values():
      if n.id not in ranks:
        max_rank += 1
        ranks[n.id] = max_rank

    rank_groups = defaultdict(list)
    for node_id, r in ranks.items():
      rank_groups[r].append(node_id)

    positions = {}
    for r, nodes in rank_groups.items():
      y = -r * self.y_spacing
      count = len(nodes)
      start_x = -((count - 1) * self.x_spacing) / 2
      for i, node_id in enumerate(nodes):
        x = start_x + (i * self.x_spacing)
        positions[node_id] = (x, y)
    return positions

  def _create_tikz_node(self, node: LogicalNode, x: float, y: float) -> TikzNode:
    """Create a TikzNode AST object for a logical node.

    Args:
        node: The LogicalNode representing the node in the graph.
        x: The computed X-coordinate for positioning the node.
        y: The computed Y-coordinate for positioning the node.

    Returns:
        TikzNode: A TikzNode AST object ready for serialization.
    """
    options = [
      TikzOption("draw"),
      TikzOption("rectangle"),
      TikzOption("rounded corners"),
      TikzOption("align", "center"),
    ]
    node_op_type: str = str(node.op_type)
    if node_op_type == "Input":
      options.append(TikzOption("fill", "green!10"))
    elif node_op_type == "Output":
      options.append(TikzOption("fill", "red!10"))
    else:
      options.append(TikzOption("fill", "blue!5"))

    bs = chr(92)
    sanitized_kind = self._sanitize(node_op_type)
    rows: list[list[str | TikzTextNode]] = [[f"{bs}textbf{{{sanitized_kind}}}"]]
    sanitized_id = self._sanitize(node.id)
    rows.append([f"{bs}textit{{{sanitized_id}}}"])

    for k, v in node.attributes.items():
      clean_k = self._sanitize(k)
      clean_v = self._sanitize(str(v)[:20])
      rows.append([f"{clean_k}: {clean_v}"])

    content_table = TikzTable(rows=rows, align="c")

    return TikzNode(
      node_id=node.id,
      x=x,
      y=y,
      content=content_table,
      options=options,
    )

  def _create_tikz_edge(self, edge: LogicalEdge) -> TikzEdge:
    """Create a TikzEdge AST object for a logical edge.

    Args:
        edge: LogicalEdge to convert.

    Returns:
        TikzEdge: The constructed TikzEdge object.
    """
    return TikzEdge(
      source_id=edge.source,
      target_id=edge.target,
      connector="--",
      options=[TikzOption("->"), TikzOption("thick")],
    )
