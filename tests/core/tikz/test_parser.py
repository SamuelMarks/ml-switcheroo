"""Unit tests for the TikZ CST parser and LogicalGraph adapter (`ml_switcheroo.core.tikz.parser`)."""

import pytest
from lark import Token, Tree
from lark.exceptions import LarkError

from ml_switcheroo.core.tikz.nodes import (
  TikzBaseNode,
  TikzEdge,
  TikzGraph,
  TikzNode,
  TikzOption,
  TikzTable,
  TriviaNode,
)
from ml_switcheroo.core.tikz.parser import TikzParser, TikzTransformer, _logical_from_tikz_graph
from ml_switcheroo.exceptions import SyntaxParseError

_NL = chr(10)
_BS = chr(92)
_NODE_CMD = _BS + "node"
_DRAW_CMD = _BS + "draw"
_ROW_SEP = _BS + _BS

SAMPLE_TIKZ = f"""
% Generated by ml-switcheroo
{_BS}begin{{tikzpicture}}[node distance=2cm, auto]
    {_NODE_CMD} [draw, fill=blue!5] (conv1) at (0, 0) {{
        {_BS}begin{{tabular}}{{c}}
            {_BS}textbf{{Conv2d}} {_ROW_SEP}
            {_BS}textit{{conv1}} {_ROW_SEP}
            kernel: 3 {_ROW_SEP}
            out: 64 {_ROW_SEP}
        {_BS}end{{tabular}}
    }};

    {_NODE_CMD} [draw, fill=red!10] (output) at (0, -3) {{
        {_BS}begin{{tabular}}{{c}}
            {_BS}textbf{{Output}} {_ROW_SEP}
            {_BS}textit{{output}} {_ROW_SEP}
        {_BS}end{{tabular}}
    }};

    {_DRAW_CMD} [->, thick] (conv1) -- (output);
{_BS}end{{tikzpicture}}
"""

VALID_TIKZ_CASES = [
  f"{_NODE_CMD} (a) at (0,0) {{A}};",
  f"{_NODE_CMD}[draw] (b) at (1,1) {{B}};",
  f"{_NODE_CMD}[draw=black] (b) at (1,1) {{B}};",
  f"{_DRAW_CMD} (a) -- (b);",
  f"{_DRAW_CMD}[thick] (a) -> (b);",
  f"{_BS}begin{{tikzpicture}} {_BS}end{{tikzpicture}}",
  f"{_BS}begin{{tikzpicture}} {_NODE_CMD} (a) at (0,0) {{A}}; {_DRAW_CMD} (a) -- (a); {_BS}end{{tikzpicture}}",
  f"{_NODE_CMD} (a) {{A}};",
  f"{_NODE_CMD}[x=1] (a) {{A}};",
  f"{_NODE_CMD} [style] (a) at (1,1) {{A}};",
]

INVALID_TIKZ_CASES = [
  _NODE_CMD,
  f"{_NODE_CMD};",
  _DRAW_CMD,
  f"{_DRAW_CMD};",
  f"{_BS}begin{{tikzpicture}} {_BS}invalid {_BS}end{{tikzpicture}}",
  "invalid { tikz {",
]


def test_parser_nodes_edges_and_escaped_metadata() -> None:
  """Verify `TikzParser` and `_logical_from_tikz_graph` extract nodes, attributes, and edges."""
  graph = _logical_from_tikz_graph(TikzParser(SAMPLE_TIKZ).parse())
  assert len(graph.nodes) == 2
  conv = graph.nodes["conv1"]
  assert conv.op_type == "Conv2d"
  assert conv.attributes == {"kernel": "3", "out": "64"}

  out = graph.nodes["output"]
  assert out.op_type == "Output"
  assert out.attributes == {}

  assert len(graph.edges) == 1
  assert graph.edges[0].source == "conv1"
  assert graph.edges[0].target == "output"

  escaped_code = f"""
{_NODE_CMD} (n) at (0,0) {{
    {_BS}begin{{tabular}}{{c}}
        {_BS}textbf{{Layer}} {_ROW_SEP}
        {_BS}textit{{n}} {_ROW_SEP}
        kernel{_BS}_size: (3, 3) {_ROW_SEP}
    {_BS}end{{tabular}}
}};
"""
  escaped_graph = _logical_from_tikz_graph(TikzParser(escaped_code).parse())
  assert escaped_graph.nodes["n"].attributes["kernel_size"] == "(3, 3)"


@pytest.mark.parametrize("case", VALID_TIKZ_CASES)
def test_valid_tikz_parsing(case: str) -> None:
  """Verify valid TikZ snippets parse into a `TikzGraph` that roundtrips via `emit()`.

  Args:
      case: Valid TikZ snippet under test.
  """
  tree = TikzParser(case).parse()
  assert isinstance(tree, TikzGraph)
  emitted = tree.emit()
  assert isinstance(emitted, str)
  assert "tikzpicture" in emitted


@pytest.mark.parametrize("case", INVALID_TIKZ_CASES)
def test_invalid_tikz_parsing(case: str) -> None:
  """Verify malformed TikZ snippets raise `SyntaxParseError` (a `ValueError` subclass).

  Args:
      case: Malformed TikZ snippet under test.
  """
  with pytest.raises((LarkError, SyntaxParseError, ValueError)):
    TikzParser(case).parse()


def test_tikz_transformer_methods_and_branches() -> None:
  """Verify `TikzTransformer` token/rule handlers, trivia partitioning, and edge cases."""
  t = TikzTransformer()

  assert t.start([]).children == []
  assert t.start([TriviaNode(" ")]).leading_trivia != []
  assert t.start([TikzNode(node_id="direct", x=0, y=0, content="c")]).children == []
  assert t.start([["node_here"], TriviaNode(" ")]).trailing_trivia != []
  assert t.start([[f"{_BS}end{{tikzpicture}}"]]).children == []
  assert t.start([["unknown_a", None]]).children == []

  nested = TikzGraph([])
  wrapped = t.start([TriviaNode(f"% lead{_NL}"), [nested], TriviaNode(f"% trail{_NL}")])
  assert wrapped is nested
  assert len(wrapped.leading_trivia) == 1
  assert len(wrapped.trailing_trivia) == 1

  assert t.element([TriviaNode(" ")]) == [TriviaNode(" ")]
  assert t.TIKZ_ENV_BEGIN(Token("TIKZ_ENV_BEGIN", f"{_BS}begin{{tikzpicture}}")) == f"{_BS}begin{{tikzpicture}}"
  assert t.TIKZ_ENV_END(Token("TIKZ_ENV_END", f"{_BS}end{{tikzpicture}}")) == f"{_BS}end{{tikzpicture}}"
  assert t.NAME(Token("NAME", "foo")) == "foo"
  assert t.OPTION(Token("OPTION", "k=v")).key == "k=v"
  assert t.COORD(Token("COORD", "1, 2")) == "1, 2"
  assert t.ALIGN(Token("ALIGN", "c")) == "c"
  assert t.EDGE_OP(Token("EDGE_OP", "--")) == "--"
  assert t.trivia([Token("WS", " "), Token("COMMENT", "% c")]).content == " % c"
  assert t.IGNORE_TEXT(Token("IGNORE_TEXT", "foo")).content == "foo"

  # Node variants: trailing trivia, invalid float coords, 3-part coords, non-text_content Tree
  node_trail = t.node([_NODE_CMD, TriviaNode(" "), "(", "n1", ")", "1.0,2.0,3.0", Tree("other", [])])
  assert isinstance(node_trail, TikzNode)
  assert node_trail.node_id == "n1"

  node_bad_float = t.node([_NODE_CMD, "n2", "a,b", Tree("text_content", [Token("TEXT", "lbl")])])
  assert node_bad_float.x == 0.0
  assert node_bad_float.content == "lbl"

  node_with_opt = t.node([TikzOption(key="draw"), Token("NAME", "n3"), Token("COORD", "2.5, -1.5")])
  assert node_with_opt.x == 2.5
  assert node_with_opt.y == -1.5

  # Edge variants: leading/trailing trivia, parentheses, options, unknown Tree child
  edge = t.edge(
    [TriviaNode(" "), _DRAW_CMD, TriviaNode(" "), "(", "s", ")", "->", "t", TikzOption("thick"), Tree("x", [])]
  )
  assert isinstance(edge, TikzEdge)
  assert edge.source_id == "s"
  assert edge.target_id == "t"
  assert edge.connector == "->"

  # Tabular rule builders and row variants
  kind_tree = t.kind([Token("KIND", "Conv2d")])
  id_tree = t.id([Token("ID", "conv1")])
  meta_tree = t.meta([Token("K", "k"), Token("COLON", ":"), Token("V", "3")])
  ign_tree = t.ignore([Token("IGN", f"extra{_ROW_SEP}")])
  row_tree = t.tabular_row([kind_tree, id_tree, meta_tree, ign_tree, Token("AMP", "&"), Tree("unknown", [])])
  empty_row_tree = t.tabular_row([])

  tab = t.tabular(
    [
      TriviaNode(" "),
      f"{_BS}begin{{tabular}}",
      TriviaNode(" "),
      "{",
      "l",
      "}",
      row_tree,
      empty_row_tree,
      Tree("not_tabular_row", []),
      f"{_BS}end{{tabular}}",
    ]
  )
  assert isinstance(tab, TikzTable)
  assert tab.align == "l"
  assert tab.rows == [[f"{_BS}textbf{{Conv2d}}", f"{_BS}textit{{conv1}}", "k: 3", "extra"]]


def test_parse_non_graph_root_raises_syntax_parse_error(monkeypatch: pytest.MonkeyPatch) -> None:
  """Verify `TikzParser.parse` raises `SyntaxParseError` if `TikzTransformer.transform` returns non-`TikzGraph`.

  Args:
      monkeypatch: Pytest monkeypatch fixture.
  """
  monkeypatch.setattr(TikzTransformer, "transform", lambda self, tree: "not_a_graph")
  with pytest.raises(SyntaxParseError, match="Expected TikzGraph root"):
    TikzParser(f"{_NODE_CMD} (a) at (0,0) {{A}};").parse()


def test_logical_from_tikz_graph_edge_cases() -> None:
  """Verify `_logical_from_tikz_graph` handles empty rows, numeric cells, non-table nodes, and empty labels."""
  node1 = TikzNode(
    node_id="n1",
    x=0,
    y=0,
    content=TikzTable(
      rows=[
        [],
        [123],
        [f"{_BS}textit{{id}}"],
        ["JustText"],
        [f"a:b{_ROW_SEP}"],
      ]
    ),
  )
  node2 = TikzNode(node_id="n2", x=0, y=0, content=TikzBaseNode())
  node3 = TikzNode(node_id="n3", x=0, y=0, content="")
  node4 = TikzNode(node_id="n4", x=0, y=0, content="Relu")
  graph = TikzGraph(children=[TriviaNode(f"% comment{_NL}"), node1, node2, node3, node4])
  lg = _logical_from_tikz_graph(graph)
  assert set(lg.nodes.keys()) == {"n1", "n2", "n3", "n4"}
  assert lg.nodes["n1"].attributes == {"a": "b"}
  assert lg.nodes["n4"].op_type == "Relu"
