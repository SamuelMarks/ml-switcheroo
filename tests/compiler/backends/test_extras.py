def test_html_backend_compile() -> None:
  """Verifies the behavior of HTML backend compile."""
  backend = HtmlBackend()
  g = LogicalGraph("TestNet")
  assert "TestNet" in backend.compile(g)
  g.nodes = [
    LogicalNode("in1", "Input"),
    LogicalNode("conv1", "Conv2d", {"arg_0": "x"}),
    LogicalNode("relu1", "func_relu", {"arg_0": "x"}),
    LogicalNode("out1", "Output"),
  ]
  g.edges = [LogicalEdge("in1", "conv1"), LogicalEdge("conv1", "relu1"), LogicalEdge("relu1", "out1")]
  html: str = backend.compile(g)
  assert "TestNet" in html
  assert "Conv2d" in html
  assert "Relu" in html


