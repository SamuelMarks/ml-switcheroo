def test_latex_backend_visited_ops() -> None:
  """Verifies the behavior of LaTeX backend visited ops."""
  from ml_switcheroo.core.compiler.backends import LatexBackend
  from ml_switcheroo.core.graph import LogicalEdge, LogicalGraph, LogicalNode
  from ml_switcheroo.semantics.manager import SemanticsManager

  backend = LatexBackend(SemanticsManager())
  graph = LogicalGraph(
    nodes=[LogicalNode("i1", "Input"), LogicalNode("i2", "Input"), LogicalNode("op", "add")],
    edges=[LogicalEdge("i1", "op"), LogicalEdge("i2", "op")],
  )
  backend.compile(graph)
  graph2 = LogicalGraph(
    nodes=[
      LogicalNode("in", "Input"),
      LogicalNode("func_add_id", "func_add", {"arg_2": "val", "kw": "2"}),
      LogicalNode("func_dot", "torch.add", {}),
    ],
    edges=[LogicalEdge("in", "func_add_id"), LogicalEdge("func_add_id", "func_dot")],
  )
  code2: str = backend.compile(graph2)
  assert "func_add" not in code2.replace("func_add_id", "replaced")
  assert "Add" in code2
  from ml_switcheroo.core.compiler.backends import HtmlBackend

  backend3 = HtmlBackend(SemanticsManager())
  code3: str = backend3.compile(graph2)
  assert "Add" in code3


